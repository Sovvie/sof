"use strict";

// Runs inside VS Code for scripts/screenshots.js. It puts the editor into each state worth a
// picture, then hands over to the outer script (which takes the screenshot) through marker
// files: <name>.ready is written when the state is up, and the next step starts when the outer
// script has written <name>.done.

const fs = require("fs");
const os = require("os");
const path = require("path");
const vscode = require("vscode");
const { startRegistry } = require("../integration/suite/mock-registry");

const SYNC_DIR = process.env.SOF_SHOT_DIR;
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

// Invented packages: the pictures illustrate the editor, not the real index.
const PACKAGES = {
  "acme/router": { description: "UI navigation with animated transitions", versions: { "1.0.0": {}, "1.4.2": {}, "2.0.0": {} } },
  "acme/stream": { description: "Reactive value streams", versions: { "1.0.0": {}, "1.2.0": {} } },
  "acme/butler": { description: "Cleanup manager for connections, tasks and Instances", versions: { "2.1.0": {}, "2.1.3": {} } },
  "acme/signal": { description: "Typed signals without the boilerplate", versions: { "3.0.0": {} } },
  "acme/state": { description: "A tiny state container", versions: { "0.4.0": {}, "0.4.1": { yanked: true } } },
  "acme/async": { description: "Token-based async helpers", versions: { "1.0.0": {} } },
  "acme/base93": { description: "Binary-to-text codec on a 93-character alphabet", versions: { "1.0.0": {} } },
  "acme/bezier": { description: "N-point Bezier curves with arc-length reparameterization", versions: { "1.0.0": {}, "1.1.0": {} } },
  "acme/buckets": { description: "Property bucketing for fast multi-property queries", versions: { "1.0.0": {} } },
  "acme/colortools": { description: "Color3 helpers with OkLab blending", versions: { "1.0.0": {} } },
  "acme/emit": { description: "Named-channel event bus", versions: { "1.0.0": {} } },
};

const SAMPLE = `[[dependencies]]
path = "src/ReplicatedStorage/Packages"
Router = "acme/router@^1.0.0"
Stream = "acme/stream@^1.2.0"
Butler = "acme/butler@2.1.0"
Signal = "acme/signal@^3.0.0"
State = "acme/state@0.4.1"
Mystery = "acme/mystery@^1.0.0"

[tools]
rojo = "rojo-rbx/rojo@7.6.1"
`;

async function handover(name) {
  fs.writeFileSync(path.join(SYNC_DIR, `${name}.ready`), "");
  const done = path.join(SYNC_DIR, `${name}.done`);
  for (let waited = 0; !fs.existsSync(done); waited += 100) {
    if (waited > 90000) throw new Error(`the screenshot of "${name}" was never taken`);
    await sleep(100);
  }
}

async function run() {
  if (!SYNC_DIR) throw new Error("SOF_SHOT_DIR is not set; run this through scripts/screenshots.js");

  const registry = await startRegistry(PACKAGES);
  const api = await vscode.extensions.getExtension("sovvie.sof").activate();

  const settings = vscode.workspace.getConfiguration("sof");
  await settings.update("registryUrl", registry.url, vscode.ConfigurationTarget.Global);
  await settings.update("wally.enabled", false, vscode.ConfigurationTarget.Global);

  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "sof-shot-"));
  const file = path.join(dir, "sof.toml");
  fs.writeFileSync(file, SAMPLE);
  // What the last install left behind: Stream was bumped to ^1.2.0 afterwards (stale), Butler was
  // added afterwards (missing), the rest are in step.
  const lockEntry = (name, alias, version) =>
    [
      "[[package]]",
      `name = "${name}"`,
      `alias = "${alias}"`,
      `version = "${version}"`,
      'source = "sof"',
      'path = "src/ReplicatedStorage/Packages"',
      'checksum = "x"',
      "",
    ].join("\n");
  fs.writeFileSync(
    path.join(dir, "sof.lock"),
    [
      "# Auto-generated by sof install. Do not edit.\n",
      lockEntry("acme/router", "Router", "1.0.0"),
      lockEntry("acme/stream", "Stream", "1.0.0"),
      lockEntry("acme/signal", "Signal", "3.0.0"),
      lockEntry("acme/state", "State", "0.4.1"),
    ].join("\n")
  );
  const document = await vscode.workspace.openTextDocument(file);
  const editor = await vscode.window.showTextDocument(document);

  for (const command of ["workbench.action.closeSidebar", "workbench.action.closePanel", "workbench.action.closeAuxiliaryBar"]) {
    await vscode.commands.executeCommand(command);
  }
  await sleep(500);
  await api.refresh(document);

  const reset = async () => {
    await vscode.commands.executeCommand("hideSuggestWidget");
    await vscode.commands.executeCommand("editor.action.hideHover");
    await vscode.commands.executeCommand("closeReferenceSearch");
    await editor.edit((edit) => edit.replace(new vscode.Range(0, 0, document.lineCount, 0), SAMPLE));
    editor.selection = new vscode.Selection(0, 0, 0, 0);
    await api.refresh(document);
    await sleep(400);
  };

  // The previous card stays up if a new one is requested while it is showing.
  const showHoverAt = async () => {
    await vscode.commands.executeCommand("editor.action.hideHover");
    await sleep(500);
    await vscode.commands.executeCommand("editor.action.showHover");
  };

  const at = (needle, extra = 0) => {
    const index = document.getText().indexOf(needle);
    return document.positionAt(index + extra);
  };

  // 1. The file as it opens: tags, squiggles, status bar.
  editor.selection = new vscode.Selection(0, 0, 0, 0);
  await sleep(800);
  await handover("tags");

  // 2. Hovering a dependency.
  const hoverAt = at("acme/router", 6);
  editor.selection = new vscode.Selection(hoverAt, hoverAt);
  await showHoverAt();
  await sleep(900);
  await handover("hover");

  // A bumped range the lock has not caught up with.
  const staleAt = at("acme/stream", 6);
  editor.selection = new vscode.Selection(staleAt, staleAt);
  await showHoverAt();
  await sleep(900);
  await handover("hover-install");

  await reset();

  // 3. Adding a dependency: type the start of a name on a new line.
  await editor.edit((edit) => edit.insert(at("Mystery"), "b\n"));
  const typed = at("b\nMystery", 1);
  editor.selection = new vscode.Selection(typed, typed);
  await vscode.commands.executeCommand("editor.action.triggerSuggest");
  await sleep(900);
  await handover("completion-names");
  await reset();

  // 4. Choosing a version.
  await editor.edit((edit) => edit.replace(new vscode.Range(at("^1.0.0"), at("^1.0.0", 6)), ""));
  const afterAt = at('acme/router@', "acme/router@".length);
  editor.selection = new vscode.Selection(afterAt, afterAt);
  await vscode.commands.executeCommand("editor.action.triggerSuggest");
  await sleep(900);
  await handover("completion-versions");
  await reset();

  // 5. The quick fix menu.
  const fixAt = at("acme/router", 4);
  editor.selection = new vscode.Selection(fixAt, fixAt);
  await sleep(300);
  await vscode.commands.executeCommand("editor.action.quickFix");
  await sleep(900);
  await handover("quickfix");

  registry.close();
}

module.exports = { run };
